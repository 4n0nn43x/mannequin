// Bundles the files the server reads at runtime, so it works wherever the platform runs it (e.g. Next standalone).
// If a source is missing (some uploaders drop ignored paths), the committed lib/engine/assets.gen.ts is kept.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
const files = ['vm/relay.js', 'vm/prepare.sh', 'runs/sample.events.jsonl']
if (!files.every(existsSync)) { console.log('embed: sources missing, keeping committed assets.gen.ts'); process.exit(0) }
const out = Object.fromEntries(files.map((f) => [f, readFileSync(f, 'utf8')]))
writeFileSync('lib/engine/assets.gen.ts', `// generated by scripts/embed.mjs, do not edit\nexport const ASSETS: Record<string, string> = ${JSON.stringify(out)}\n`)
